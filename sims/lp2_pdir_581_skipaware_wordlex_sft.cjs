/** @param {Array<{word:string,p:number[]}>} entries */
function makeTrie(entries){
  const edge=[new Int32Array(29).fill(-1)],ends=[''];
  for(const {word,p} of entries){
    let node=0;
    for(const digit of p){
      let next=edge[node][digit];
      if(next===-1){
        next=edge.length;edge[node][digit]=next;
        edge.push(new Int32Array(29).fill(-1));ends.push('');
      }
      node=next;
    }
    ends[node]=word;
  }
  return {edge,ends};
}
