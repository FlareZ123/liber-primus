/** @param {Buffer} data @returns {Array<{name:string,key:Uint8Array}>} */
function parseLibrary(data){
  assert.equal(data.toString('ascii',0,4),'KSB1');
  let n=data.readUInt32LE(4),pos=8;
  assert.equal(n,expectedKeyCount);
  const streams=[];
  for(let i=0;i<n;i++){
    const labelSize=data.readUInt16LE(pos);pos+=2;
    const name=data.toString('utf8',pos,pos+labelSize);pos+=labelSize;
    const len=data.readUInt32LE(pos);pos+=4;
    const key=data.subarray(pos,pos+len);pos+=len;
    assert.equal(key.length,len);
    streams.push({name,key});
  }
  assert.equal(pos,data.length);
  return streams;
}
