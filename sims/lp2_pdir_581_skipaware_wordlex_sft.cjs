/**
 * A whole-word trie reachability test against one key/starting offset.
 * Every one of 18 source conventions is contained, since h/m shift only
 * the unknown word starting phase, and c affects only the first backwards
 * rune. Grant 0,1,2 first-rune skips regardless of comparator to contain
 * those first-rune possibilities, and even extra first coin behavior.
 * @param {number[]} cipher @param {Uint8Array} K
 * @param {{edge:Int32Array[],ends:string[]}} trie
 * @param {number} sign @param {number} dir @param {number} model
 * @returns {(start:number)=>string}
 */
function buildReacher(cipher,K,trie,sign,dir,model){
  const N=cipher.length,edge=trie.edge,ends=trie.ends,klen=K.length;
  /** @param {number} i @param {number} j @param {number} node @returns {string} */
  function go(i,j,node){
    if(i===N)return ends[node];
    const c=cipher[i],prev=i?cipher[i-1]:-1,first=i===0;
    if(j<0||j>=klen)return '';
    const k0=K[j];
    // Direct emission, both models. Unknown first comparator can consume
    // a coin even when the same ciphertext rune is emitted.
    const p0=mod(c-sign*k0);
    let child=edge[node][p0];
    if(child!==-1){
      let shift=model===1&&prev===c?2:1;
      let result=go(i+1,j+dir*shift,child);
      if(result)return result;
      if(first&&model===1){
        result=go(i+1,j+dir*2,child);
        if(result)return result;
      }
    }
    if(model===0){
      for(let skip=1;skip<=2;skip++){
        const idx=j+dir*skip;
        if(idx<0||idx>=klen)break;
        const ks=K[idx],p=mod(c-sign*ks);
        if(!first){
          let rejects=true;
          for(let s=0;s<skip;s++){
            const prior=K[j+s*dir];
            if(mod(p+sign*prior)!==prev){rejects=false;break;}
          }
          if(!rejects)continue;
        }
        child=edge[node][p];
        if(child<0)continue;
        const result=go(i+1,idx+dir,child);
        if(result)return result;
      }
    }else{
      // Model1: one two-position skip, the intermediate key is the coin.
      const idx=j+2*dir;
      if(idx>=0&&idx<klen){
        const p=mod(c-sign*K[idx]);
        if(first||mod(p+sign*k0)===prev){
          child=edge[node][p];
          if(child!==-1){
            const result=go(i+1,idx+dir,child);
            if(result)return result;
          }
        }
      }
    }
    return '';
  }
  return start=>go(0,start,0);
}

/** @param {number[]} cipher @param {{name:string,key:Uint8Array}[]} streams @returns {object|null} */
function findPreimage(cipher, streams){
  const trie=tries.get(cipher.length);
  if(!trie)return null;
  for(const {name,key} of streams){
    for(const sign of [1,28]){
      for(const direction of [1,-1]){
        for(const model of [0,1]){
          const test=buildReacher(cipher,key,trie,sign,direction,model);
          for(let start=0;start<key.length;start++){
            const word=test(start);
            if(word)return {word,key:name,sign,direction,model,start};
          }
        }
      }
    }
  }
  return null;
}

