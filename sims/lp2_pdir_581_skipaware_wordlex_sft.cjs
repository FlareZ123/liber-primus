/** @param {string} raw @returns {number[]} */
function encode(raw){
  const s=raw.toUpperCase().replace(/QU/g,'CW').replace(/V/g,'U')
    .replace(/[KQ]/g,'C').replace(/Z/g,'S');
  const out=[];
  for(let j=0;j<s.length;){
    if(s.startsWith('ING',j)){out.push(21);j+=3;continue;}
    if(s.startsWith('IO',j)){out.push(27);j+=2;continue;}
    const t=tok.find(t=>s.startsWith(t.s,j));
    if(!t)return [];
    out.push(t.i);j+=t.s.length;
  }
  return out;
}
