'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const t=require('./wordlength_transposition');
const master=fs.readFileSync(path.join(__dirname,'..','resources','transcriptions','liber_primus_master.txt'),'utf8');
const corpus=t.groupSizes(master);
assert.equal(corpus.lengths.length,2896);
assert.equal(corpus.pages.length,56);
assert.equal(corpus.pages[50],0);
assert.equal(corpus.pages.reduce((a,b)=>a+b,0),2896);
assert.equal(corpus.segments.reduce((a,b)=>a+b,0),2896);
const specs=t.transformSpecs(corpus);
assert.equal(specs.length,276);
assert.deepEqual(t.localPermutation(6,3,'fwd'),[0,3,1,4,2,5]);
assert.deepEqual(t.localPermutation(6,3,'inverse'),[0,2,4,1,3,5]);
const results=t.evaluateTransformFamily(corpus,20);
assert.equal(results.tested,276);
assert.equal(results.top[0].name,'segment_rail_8');
assert.ok(Math.abs(results.top[0].chi2-14.41535628634031)<1e-8);
console.log(JSON.stringify({grouping:{pageSizes:corpus.pages,segmentSizes:corpus.segments},results},null,2));
console.log('All transposition regression checks passed');
