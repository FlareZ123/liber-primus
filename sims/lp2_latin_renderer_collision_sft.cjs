'use strict';
// Run from the repository root: node sims/lp2_latin_renderer_collision_sft.cjs
const fs=require('node:fs');
const assert=require('node:assert/strict');
const read=p=>fs.readFileSync(p,'utf8');
const c=JSON.parse(read('resources/liber-primus/lp2-corpus.json'));
const n=JSON.parse(read('resources/external/relikd-solved-gp29-native-v1.json'));
const a=c.runes,t=c.translit,map=new Map(a.map((x,i)=>[x,i])),back=new Map(t.map((x,i)=>[x,i]));
const tape=s=>[...s].filter(x=>map.has(x)).map(x=>map.get(x));
const groups=s=>s.replace(/[\/\s]/gu,'').match(new RegExp('['+a.join('')+']+','gu'))||[];
const p=read('resources/transcriptions/lp1_wulfic_canonical.txt').trim().split('%');
const q=read('resources/transcriptions/lp2-image-corrected.txt').trim().split('%');
const native=n.sections.map(s=>tape(s.source_text));
const mod=x=>(x%29+29)%29;
const lat=s=>tape(s).map(i=>t[i]).join('');
const encode=(p,k)=>{let j=0;return p.map(x=>x===0?0:mod(x+k[j++%k.length]));};
const key=s=>[...s].map(x=>t.indexOf(x));
const primes=[];for(let i=2;primes.length<85;i++)if(primes.every(p=>i%p))primes.push(i);
const paint=(s,plain)=>{let j=0;const out=[...s].map(x=>map.has(x)?a[plain[j++]]:x).join('');assert.equal(j,plain.length);return out;};
const check=(s,plain,k)=>{assert.deepEqual(encode(plain,k),tape(s));return paint(s,plain);};
const train=[paint(p[0],tape(p[0]).map(x=>28-x)),check(p.slice(1,3).join(''),native[1],key('DIUINITY')),p[3],paint(p.slice(4,8).join(''),tape(p.slice(4,8).join('')).map(x=>mod(2-x))),p.slice(8,12).join(''),check(p.slice(12,14).join(''),native[5],key('FIRFUMFERENFE')),p[14]];
const held=[check(q[55],native[7],primes.map(x=>x-1)),q[56]];
assert.deepEqual(tape(train[0]),native[0]);
const digs=t.filter(s=>s.length===2);
const render=(s,mask)=>{let out='';for(let i=0;i<s.length;){const j=digs.indexOf(s.slice(i,i+2));const len=j>=0&&(mask&(1<<j))?2:1;out+=a[back.get(s.slice(i,i+len))];i+=len;}return out;};
const all=train.flatMap(groups),h=held.flatMap(groups),orig=groups(q.slice(0,55).join(''));
assert.equal(all.length,694);assert.equal(h.length,45);assert.equal(orig.length,2896);
const masks=Array.from({length:128},(_,i)=>i).filter(m=>all.every(w=>render(lat(w),m)===w));
const stats=masks.map(m=>({m,heldErrors:h.filter(w=>render(lat(w),m)!==w).length,originalErrors:orig.filter(w=>render(lat(w),m)!==w).length}));
assert.deepEqual(stats,[{m:117,heldErrors:0,originalErrors:858},{m:119,heldErrors:0,originalErrors:559},{m:125,heldErrors:0,originalErrors:492},{m:127,heldErrors:0,originalErrors:175}]);
const inv=new Map();orig.forEach((w,i)=>{const x=lat(w);if(!inv.has(x))inv.set(x,new Map());const y=inv.get(x);if(!y.has(w))y.set(w,[]);y.get(w).push(i);});
const collisions=[...inv].filter(([,v])=>v.size>1).map(([s,v])=>({s,variants:[...v]}));
const lowerBound=collisions.reduce((s,x)=>s+x.variants.reduce((n,[,v])=>n+v.length,0)-Math.max(...x.variants.map(([,v])=>v.length)),0);
assert.equal(collisions.length,7);assert.equal(lowerBound,8);
console.log(JSON.stringify({training:train.map(s=>({runes:tape(s).length,groups:groups(s).length})),held:held.map(s=>({runes:tape(s).length,groups:groups(s).length})),digraphCounts:digs.map(d=>[d,all.flatMap(tape).filter(i=>t[i]===d).length]),stats,collisions,lowerBound},null,2));
