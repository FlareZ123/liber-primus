'use strict';

/**
 * Verify the exact default OutGuess 0.4 embedding seed search range using
 * the same frozen upstream source revision as the repository's original
 * extractor, without conjecturing cryptographic keys or image alterations.
 * Run: node sims/lp1_04_outguess_default_seed_source_sft.cjs
 */
const assert = require('node:assert/strict');
const { createHash } = require('node:crypto');

const revision = '24810e14327c2bbeedeaadd3e24491f2a4425c02';
const upstream = 'https://raw.githubusercontent.com/resurrecting-open-source-projects/outguess/' + revision + '/src/';

async function original(path) {
  const response = await fetch(upstream + path, {
    headers: { 'User-Agent': 'LP1-DefaultSeed-Original-SFT' },
  });
  assert.equal(response.status, 200, 'pinned source must be obtainable');
  const text = await response.text();
  return {
    source: text,
    sha256: createHash('sha256').update(text).digest('hex'),
  };
}

(async function main() {
  const [iterator, outguess] = await Promise.all([
    original('iterator.h'),
    original('outguess.c'),
  ]);
  const define = /#define\s+DEFAULT_ITER\s+(\d+)\s*$/m.exec(iterator.source);
  assert.ok(define, 'the default embedding iterations are explicit in upstream');
  const limit = Number(define[1]);
  assert.equal(limit, 256, 'this pinned OutGuess 0.4 revision selects 256 trials');
  assert.match(outguess.source, /if\s*\(!siter\s*&&\s*!siterstart\)\s*siter\s*=\s*DEFAULT_ITER\s*;/);
  assert.match(outguess.source, /for\s*\(i\s*=\s*siterstart;\s*i\s*<\s*siter;\s*i\+\+\)/);
  assert.match(outguess.source, /steg_find\(bitmap,\s*&iter,\s*&as,\s*cfg->siter,\s*cfg->siterstart,/);
  assert.match(outguess.source, /case\s*'i':\s*cfg1\.siter\s*=\s*atoi\(optarg\)\s*;/);
  assert.match(outguess.source, /case\s*'s':\s*cfg1\.siterstart\s*=\s*atoi\(optarg\)\s*;/);

  const positiveSourceNativeSeeds = { '00.jpg': 163, '03.jpg': 127, '08.jpg': 38 };
  const p04SourceNativeSeed = 38370;
  for (const [name, seed] of Object.entries(positiveSourceNativeSeeds)) {
    assert.ok(seed >= 0 && seed < limit, name + ' authentic original default embedding seed');
  }
  assert.ok(p04SourceNativeSeed >= limit,
    '04.jpg recovered header cannot have been generated by default embedding seed search');
  process.stdout.write(JSON.stringify({
    pinnedSourceRevision: revision,
    exactSourceSha256: { iterator_h: iterator.sha256, outguess_c: outguess.sha256 },
    defaultEmbeddableSeedHalfOpenInterval: [0, limit],
    authenticSourceNativeControls: positiveSourceNativeSeeds,
    original04RecoveredSeed: p04SourceNativeSeed,
    original04WithinDefaultSeedRange: false,
    limitation: 'This excludes unmodified default OutGuess embedding of this exact 04.jpg header, but not explicit -i/-s overrides, independent manipulation of the JPEG, or a chance decoder header. No payload decipherment.',
  }, null, 2) + '\n');
})().catch(err => { process.stderr.write(err.stack + '\n'); process.exitCode = 1; });
