/**
 * Source-registered 32x8 row bridge: any secret stationary linear/affine GF29
 * map from p49-51 printed base60 byte rows to the unique original p8->p9
 * 256-rune frame. All 8×8 maps are included, not a key search.
 * Node.js 22 CommonJS; zero external dependencies.
 */
'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const corpus = JSON.parse(fs.readFileSync(path.join(root, 'resources/liber-primus/lp2-corpus.json'), 'utf8'));
const grid = JSON.parse(fs.readFileSync(path.join(root, 'resources/liber-primus/lp2-grid-256.json'), 'utf8'));
const pg = n => corpus.pages.find(x => x.page === n).indices;
const rune = [...pg(8).slice(4), ...pg(9).slice(0, 5)];
assert.equal(rune.length, 256);
assert.equal(grid.bytes.length, 256);
const p = 29;
const mod = x => (x % p + p) % p;
const inverse = a => {
  for (let k = 1; k < p; k++) if (mod(a*k) === 1) return k;
  throw Error('singular pivot ' + a);
};
const x = Array.from({length:32},(_,i)=>grid.bytes.slice(8*i,8*i+8).map(v=>v%29));
const y = Array.from({length:32},(_,i)=>rune.slice(8*i,8*i+8));

/**
 * Exact Gaussian elimination, all output columns simultaneously.
 * Source row-major GF29 X. Affine adds a ninth all-one column.
 * @param {number[][]} input
 * @param {number[][]} target
 * @param {number[]} rows
 * @param {boolean} affine
 */
function solve(input,target,rows,affine) {
  const dim=affine?9:8;
  const a=rows.map(i=>[...input[i],...(affine?[1]:[]),...target[i]]);
  let rank=0,cols=[];
  for(let j=0;j<dim;j++){
    const pivot=a.findIndex((r,k)=>k>=rank&&r[j]!==0);
    if(pivot<0)continue;
    [a[rank],a[pivot]]=[a[pivot],a[rank]];
    const den=inverse(a[rank][j]);
    for(let c=0;c<dim+8;c++)a[rank][c]=mod(a[rank][c]*den);
    for(let r=0;r<a.length;r++)if(r!==rank&&a[r][j]){
      const b=a[r][j];
      for(let c=0;c<dim+8;c++)a[r][c]=mod(a[r][c]-b*a[rank][c]);
    }
    cols.push(j); rank++;
  }
  const contradictory=a.filter(row=>row.slice(0,dim).every(z=>z===0)&&row.slice(dim).some(z=>z!==0)).length;
  if(rank<dim)return{rank,contradictory,matrix:null};
  const matrix=Array.from({length:dim},()=>new Array(8).fill(0));
  for(let i=0;i<rank;i++)for(let c=0;c<8;c++)matrix[cols[i]][c]=a[i][dim+c];
  return{rank,contradictory,matrix};
}
/** @param {number[]} src @param {number[][]} matrix */
function apply(src,matrix) {
  return Array.from({length:8},(_,c)=>mod(src.reduce((s,v,k)=>s+v*matrix[k][c],matrix.length===9?matrix[8][c]:0)));
}
function evaluate(rows,affine,input=x,target=y){
  const fit=solve(input,target,rows,affine);
  if(!fit.matrix || fit.contradictory) return {...fit,train:rows.length};
  const matches=Array.from({length:32},(_,i)=>apply(input[i],fit.matrix).reduce((s,v,c)=>s+Number(v===target[i][c]),0));
  return{rank:fit.rank,contradictory:fit.contradictory,train:rows.length,
    trainMatches:rows.reduce((s,i)=>s+matches[i],0),
    rubricMatches:matches[0],
    holdoutMatches:matches.slice(1).reduce((s,z,i)=>s+(!rows.includes(i+1)?z:0),0),
    blackHoldoutCells:(31-rows.length)*8,fullMatches:matches.reduce((s,z)=>s+z,0),
    firstTwoRowsOfMatrix:fit.matrix.slice(0,2)};
}
const black31=Array.from({length:31},(_,i)=>i+1);
const lin8=evaluate(black31.slice(0,8),false);
const aff9=evaluate(black31.slice(0,9),true);
const impossibleLin=solve(x,y,black31,false);
const impossibleAff=solve(x,y,black31,true);
assert.equal(lin8.rank,8);assert.equal(lin8.trainMatches,64);
assert.equal(lin8.rubricMatches,1);assert.equal(lin8.holdoutMatches,5);
assert.equal(aff9.rank,9);assert.equal(aff9.trainMatches,72);
assert.equal(aff9.rubricMatches,0);assert.equal(aff9.holdoutMatches,7);
assert.ok(impossibleLin.contradictory>0);
assert.ok(impossibleAff.contradictory>0);

// Construct a native control with an invertible but nontrivial mixing matrix:
// exact same original source input; all 32 outputs generated by a legitimate map.
const knownM=Array.from({length:8},(_,i)=>Array.from({length:8},(_,j)=>Number(i===j)));
knownM[0][1]=2;knownM[6][7]=4;
const plant=x.map(row=>apply(row,knownM));
const planted=evaluate(black31.slice(0,8),false,x,plant);
assert.equal(planted.trainMatches,64);
assert.equal(planted.holdoutMatches,23*8);
assert.equal(planted.fullMatches,256);

// Affine independent native control.
const knownAff=knownM.map(row=>row.slice()).concat([new Array(8).fill(5)]);
const affPlant=x.map(row=>apply(row,knownAff));
const plantedAff=evaluate(black31.slice(0,9),true,x,affPlant);
assert.equal(plantedAff.holdoutMatches,22*8);
assert.equal(plantedAff.fullMatches,256);
console.log(JSON.stringify({frameLength:rune.length,tableValues:grid.bytes.length,firstRubric:rune.slice(0,8),
  linear:lin8,affine:aff9,
  allBlackRowsLinearContradictory:impossibleLin.contradictory,
  allBlackRowsAffineContradictory:impossibleAff.contradictory,
  positiveNativeLinear:planted.fullMatches,positiveNativeAffine:plantedAff.fullMatches},null,2));
console.log('PASS: any unknown source-registered stationary GF29 row linear or affine p8/table bridge is inconsistent');
