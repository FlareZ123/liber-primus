"""Original May-2014 UnRuneIt JAR bytecode differential. Read-only, no JAR execution.
Original GitHub Actions capture ZIP via --archive or files generated by the
existing source-native 2014 MediaFire acquisition SFT. Requires JDK javap.
"""
from __future__ import annotations
import argparse
import hashlib
import io
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile
import zipfile

EXPECTED = {
    1: (766148, "e465e31a5b46dbeeecae337caf1d195b17f6ab7c9596479b56b1f08690a4df16",
        "b0ba7495098ab64564efa7d8504a174064fbae0994c79f3e5116ed2b256b2e45"),
    2: (767453, "b4a66f04837c368f04dab2a8573ab1da5d67b978f4cc4709c551f8913c900fb6",
        "fd9e5ce267f0ed3c67617597689d48649558d8f5eaf17162858bb41563e87f51"),
}

def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()

def read_source(archive: str | None) -> dict[int, bytes]:
    if archive:
        with zipfile.ZipFile(archive) as original:
            data = {v: original.read(f"unrune{v}.jar") for v in EXPECTED}
    else:
        directory = Path("irc-2014-nonpaste-live")
        data = {v: (directory / f"unrune{v}.jar").read_bytes() for v in EXPECTED}
    for version, binary in data.items():
        length, digest, _ = EXPECTED[version]
        assert len(binary) == length and sha256(binary) == digest
    return data

def javap(raw_class: bytes, directory: Path, version: int) -> str:
    target = directory / f"v{version}" / "UnRuneIt.class"
    target.parent.mkdir(exist_ok=True)
    pending = target.with_suffix(".class.partial")
    with pending.open("xb") as handle:
        handle.write(raw_class)
        handle.flush()
        os.fsync(handle.fileno())
    pending.replace(target)
    return subprocess.run(
        ["javap", "-p", "-c", str(target)],
        check=True, capture_output=True, text=True, encoding="utf-8"
    ).stdout

def methods(text: str) -> set[str]:
    return set(re.findall(
        r"^  ((?:public|private|protected) [^\n]*\([^\n]*\);)$",
        text, flags=re.M))

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", type=str, default=None)
    args = parser.parse_args()
    binaries = read_source(args.archive)
    hashes: dict[int, dict[str, str]] = {}
    disassemblies: dict[int, str] = {}
    with tempfile.TemporaryDirectory(prefix="lp2-2014-unrune-") as folder:
        for version, binary in binaries.items():
            with zipfile.ZipFile(io.BytesIO(binary)) as jar:
                files = {entry.filename: sha256(jar.read(entry))
                         for entry in jar.infolist() if not entry.is_dir()}
                cls = jar.read("UnRuneIt.class")
            assert files["UnRuneIt.class"] == EXPECTED[version][2]
            hashes[version] = files
            disassemblies[version] = javap(cls, Path(folder), version)
    assert hashes[1].keys() == hashes[2].keys()
    changed = sorted(p for p in hashes[1] if hashes[1][p] != hashes[2][p])
    assert changed == ["UnRuneIt.class"] and len(hashes[1]) == 15
    v1, v2 = methods(disassemblies[1]), methods(disassemblies[2])
    assert (len(v1), len(v2)) == (21, 30)
    removed, added = sorted(v1-v2), sorted(v2-v1)
    assert len(removed) == 2 and len(added) == 11
    assert "private java.lang.String decipher(java.lang.String, int[]);" not in v1
    assert "private java.lang.String[] unShift(java.lang.String, int);" not in v1
    assert "Enter your choice:" in disassemblies[1]
    assert "Enter word to decipher:" not in disassemblies[1]
    assert "You need to paste" not in disassemblies[1]
    assert "private java.lang.String decipher(java.lang.String, int[]);" in v2
    assert "private java.lang.String[] unShift(java.lang.String, int);" in v2
    assert "You need to paste" in disassemblies[2]
    assert "Enter keyword in integers:" in disassemblies[2]
    assert " of primes in this format 2 3 5 7" in disassemblies[2]
    assert "private int getRunePrime(java.lang.String);" in v2
    assert "private java.util.ArrayList<java.lang.String> compileWordlist(int, java.util.ArrayList<java.lang.String>);" in v1
    assert re.search(r"\b563: bipush\s+79\s*\n\s*565: iastore", disassemblies[1])
    assert re.search(r"\b563: bipush\s+21\s*\n\s*565: iastore", disassemblies[2])
    print(json.dumps({
        "original_jar_sha256": {v: EXPECTED[v][1] for v in (1, 2)},
        "only_changed_jar_member": changed,
        "identical_jar_members": 14,
        "v1_methods": len(v1), "v2_methods": len(v2),
        "removed_signatures": removed, "added_signatures": added,
        "v1_contains_decryptor": False,
        "v2_requires_user_supplied_prime_tape": True,
        "INDEXES_correction": "element26:79->21",
        "JARs_executed": False,
        "unknown_LP2_plaintext_or_key": False
    }, indent=2))

if __name__ == "__main__":
    main()
