for(const [n,s] of [['raw',pack(raw)],['donor',pack(donor)],['prior',B.sections.filter(s=>!names.includes(s.name)).map(s=>pack(gp(s))).join('\n')]])fs.writeFileSync(path.join(out,n+'.txt'),s+'\n');
