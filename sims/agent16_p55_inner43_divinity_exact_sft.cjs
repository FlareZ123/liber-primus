"use strict";
/**
 * Exact source-led p55 interior gate.
 *
 * Solved p57 says "shed our own circumferences, find the divinity within".
 * The source-exact p55 word peel yields 43 strict interior runes. Test that
 * interior under the authenticated LP1 DIVINITY period-8 GP29 cipher with
 * its real plaintext-F bypass rule. Every possible ciphertext-F bypass mask
 * is enumerated. No key, phase, sign, ordering, or language score is fitted.
 *
 * Windows Node22 CJS, read-only, no dependencies.
 */
const assert=require("node:assert/strict");
const corpus=require("../resources/liber-primus/lp2-corpus.json");
const {split}=require("./lp2_p55_circumference_two_stream_feistel_sft.cjs");
const authentic=require("./authentic_lp1_p03_p04_vigenere_recovery.cjs");
const key=authentic.key;
assert.deepEqual(key,[23,10,1,10,9,10,16,26]);

const p55=corpus.pages.find(p=>p.page===55).indices;
const interior=split(p55).interior;
assert.equal(interior.length,43);
assert.deepEqual(interior,
  [19,10,12,6,23,2,27,24,17,5,28,0,14,10,19,1,5,13,8,21,20,15,23,27,13,8,12,18,10,6,14,6,15,12,2,2,18,28,10,19,5,11,18]);
const fpos=interior.flatMap((x,i)=>x===0?[i]:[]);
assert.deepEqual(fpos,[11]);
const mod=x=>((x%29)+29)%29;

function decode(mask){
  const out=[];
  let phase=0;
  for(let i=0;i<interior.length;i++){
    const fi=fpos.indexOf(i);
    const bypass=fi>=0&&((mask>>fi)&1)!==0;
    if(bypass){out.push(0);continue;}
    const p=mod(interior[i]-key[phase]);
    if(p===0)return null;
    out.push(p);
    phase=(phase+1)%key.length;
  }
  return out;
}

const valid=[];
for(let mask=0;mask<(1<<fpos.length);mask++){
  const out=decode(mask);
  if(out)valid.push({mask,out});
}
assert.equal(valid.length,0,
  "no p55 interior bypass assignment may satisfy the authentic DIVINITY law");

assert.equal(authentic.cipher.length,515);
assert.equal(authentic.plaintext.length,515);
assert.equal(authentic.allRecoveredFs.length,11);
assert.deepEqual(authentic.allRecoveredFs,
  [48,74,84,132,159,160,250,421,443,465,514]);

console.log("SOURCE",JSON.stringify({
  p55PageRunes:p55.length,
  strictInteriorRunes:interior.length,
  ciphertextFPositions:fpos,
  divinityKeyIndices:key
}));
console.log("BYPASS_MASKS_ENUMERATED",1<<fpos.length);
console.log("STRICT_VALID_MASKS",valid.length);
console.log("AUTHENTIC_LP1_CONTROL",JSON.stringify({
  runes:authentic.cipher.length,
  literalFBypasses:authentic.allRecoveredFs.length,
  status:"PASS"
}));
console.log("DECISION",
  "The exact p55 43-rune interior cannot be generated by the authentic LP1 DIVINITY cipher at phase0 under any legal plaintext-F bypass assignment.");
