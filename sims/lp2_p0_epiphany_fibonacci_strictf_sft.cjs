"use strict";
/**
 * Source-constrained, conditional LP2 p0 EPIPHANY SEEKS Fibonacci-key gate.
 *
 * The original 2016 signed sentence contains "epiphany seeks", whose
 * GP29 word lengths match the original p0 red 8-5 heading. The 13-rune
 * presumed plaintext determines a 13-symbol additive key. This test
 * checks six exact 5/8/13-lag Fibonacci recurrences as possible key
 * extensions under the authentic p56 plaintext-F transparency rule.
 *
 * No unknown LP2 plaintext, title authentication, or key is asserted.
 * Standalone test: node sims/lp2_p0_epiphany_fibonacci_strictf_sft.cjs
 */
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
/** @param {string} relative @returns {string} */
const read = relative => fs.readFileSync(path.join(root, relative), "utf8");
const corpus = JSON.parse(read("resources/liber-primus/lp2-corpus.json"));
const signed = read("resources/historical/cicada2016-4gq25-outguess.asc");
const MOD = 29;
const TITLE = "EPIPHANYSEECS";
const EXPECTED_SEED = [26, 24, 8, 19, 27, 24, 18, 3, 0, 8, 0, 16, 19];

/** @param {number} n @returns {number} */
function mod(n) { return ((n % MOD) + MOD) % MOD; }

/**
 * @param {number[]} seed
 * @param {number} n
 * @param {number} lagA
 * @param {number} lagB
 * @param {number} sign
 * @returns {number[]}
 */
function extend(seed, n, lagA, lagB, sign) {
  const key = seed.slice();
  for (let i = key.length; i < n; i++) {
    key.push(mod(key[i - lagA] + sign * key[i - lagB]));
  }
  return key;
}

/**
 * Exhaustively propagate legal consumed-key clocks. In the authentic
 * historical decoder, plaintext F (index 0) must be transmitted as
 * ciphertext F and does not consume a key. Ciphertext F is ambiguous:
 * it may also be generated by a keyed non-F plaintext rune.
 *
 * @param {number[]} cipher
 * @param {number[]} key
 * @param {number} initialOffset
 * @param {number} initialClock
 * @returns {{offset:number,cipher:number,candidateKeys:Array<{clock:number,key:number}>}|null}
 */
function firstFailure(cipher, key, initialOffset, initialClock) {
  let clocks = new Set([initialClock]);
  for (let i = initialOffset; i < cipher.length; i++) {
    const next = new Set();
    for (const clock of clocks) {
      assert.ok(clock < key.length, "Missing key symbol for legal clock");
      if (cipher[i] === 0) {
        next.add(clock); // literal plaintext-F bypass
        if (key[clock] !== 0) next.add(clock + 1); // keyed non-F
      } else if (key[clock] !== cipher[i]) {
        next.add(clock + 1); // non-F plaintext must be nonzero
      }
    }
    if (next.size === 0) {
      return {
        offset: i, cipher: cipher[i],
        candidateKeys: [...clocks].map(clock => ({clock, key: key[clock]}))
      };
    }
    clocks = next;
  }
  return null;
}

/**
 * @param {number[]} plaintext
 * @param {number[]} key
 * @returns {{cipher:number[],clock:number}}
 */
function encryptTransparentF(plaintext, key) {
  let clock = 0;
  const cipher = [];
  for (const p of plaintext) {
    if (p === 0) {
      cipher.push(0);
    } else {
      assert.ok(clock < key.length);
      cipher.push(mod(p + key[clock]));
      clock++;
    }
  }
  return {cipher, clock};
}

/** @returns {void} */
function run() {
  assert.match(signed, /epiphany seeks/i);
  const p0 = corpus.pages.find(p => p.page === 0);
  const p1 = corpus.pages.find(p => p.page === 1);
  const p2 = corpus.pages.find(p => p.page === 2);
  const p57 = corpus.pages.find(p => p.page === 57);
  assert.deepEqual([p0.runic_count, p1.runic_count, p2.runic_count], [262, 266, 201]);
  assert.equal(p57.runic_count, 95);
  const cipher = [...p0.indices, ...p1.indices, ...p2.indices];
  assert.equal(cipher.length, 729);
  assert.equal(TITLE.length, 13);
  const title = [...TITLE].map(ch => {
    const index = corpus.translit.indexOf(ch);
    assert.ok(index >= 0, "Unsupported presumed-title rune " + ch);
    return index;
  });
  assert.ok(title.every(p => p !== 0), "Title seed has no plaintext F");
  const seed = title.map((p, i) => mod(cipher[i] - p));
  assert.deepEqual(seed, EXPECTED_SEED);
  assert.deepEqual(
    cipher.slice(0, title.length),
    title.map((p, i) => mod(p + seed[i]))
  );

  const cases = [
    {a:13,b:8,sign: 1,expected:60},
    {a:13,b:8,sign:-1,expected:13},
    {a:13,b:5,sign: 1,expected:109},
    {a:13,b:5,sign:-1,expected:163},
    {a: 8,b:5,sign: 1,expected:172},
    {a: 8,b:5,sign:-1,expected:143}
  ];
  const results = [];
  for (const test of cases) {
    // 729 slots suffice: a plaintext-F bypass can only reduce key usage.
    const key = extend(seed, cipher.length, test.a, test.b, test.sign);
    const failure = firstFailure(cipher, key, title.length, title.length);
    assert.ok(failure, "Expected original-cipher F contradiction");
    assert.equal(failure.offset, test.expected);

    // Independent solved p57 plaintext supplies a source-native plant.
    // Retain the same hypothesized 13-rune title at the start so that
    // its initial clock and presumed key agree with the original crib.
    const plaintext = title.concat(
      Array.from({length:cipher.length-title.length},
        (_,i) => p57.indices[i % p57.indices.length])
    );
    const planted = encryptTransparentF(plaintext, key);
    assert.deepEqual(planted.cipher.slice(0, title.length),
      cipher.slice(0, title.length));
    assert.equal(firstFailure(planted.cipher, key, title.length,
      title.length), null, "The true key must remain a legal path");
    // Every original constraint above can be contradicted without
    // ever choosing between the two meanings of ciphertext F.
    results.push({
      lagA:test.a,lagB:test.b,sign:test.sign,
      firstImpossibleOriginalRuneZeroBased:failure.offset,
      originalCipherRune:corpus.translit[failure.cipher],
      survivingClocks:failure.candidateKeys.map(x => x.clock),
      forcedKeyRunes:failure.candidateKeys.map(x => corpus.translit[x.key]),
      plantedLength:planted.cipher.length,
      plantedFullInverseAccepted:true
    });
  }
  console.log(JSON.stringify({
    hypothesis:"conditional unverified p0 red-title crib and p56-style transparent-F cipher",
    signedPhrase:"EPIPHANY SEEKS",
    keySeedGpIndices:seed,
    firstChapterRuneCount:cipher.length,
    results,
    recoveredUnknownPlaintext:false
  }, null, 2));
}
if (require.main === module) run();
module.exports = {run,extend,firstFailure,encryptTransparentF};
