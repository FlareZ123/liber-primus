"use strict";
const assert=require("node:assert/strict");
const mod=(x,m)=>((x%m)+m)%m;
const inv=(x,m)=>{for(let a=1;a<m;a++) if(mod(a*x,m)===1) return a; return null;};
const state={K:2,e:3,q:4,g:5,a:6,A:8,b:15,B:19,p:23,minusE:26};
const known=[{row:state.K,value:state.b,label:"K->b"},{row:state.minusE,value:state.a,label:"-e->a"},{row:state.p,value:state.B,label:"p->B"}];
const relations=[];
const add=(name,fn)=>relations.push({name,outputs:known.map(k=>fn(k.row)),matches:known.map(k=>fn(k.row)===k.value)});
add("inverse mod29",x=>inv(mod(x,29),29));
add("negative inverse mod29",x=>mod(-inv(mod(x,29),29),29));
for(const [name,e] of Object.entries({K:state.K,e:state.e,q:state.q,g:state.g,a:state.a,b:state.b})) add(`x^${name} mod p`,x=>Number(BigInt(mod(x,state.p))**BigInt(e)%BigInt(state.p)));
add("g^x mod p",x=>Number(BigInt(state.g)**BigInt(mod(x,state.p-1))%BigInt(state.p)));
const affine=[];
for(let m=0;m<29;m++) for(let c=0;c<29;c++) if(known.every(k=>mod(m*k.row+c,29)===k.value)) affine.push({m,c});
assert.equal(affine.length,0);
const reciprocalScale=[];
for(let c=0;c<29;c++) if(known.every(k=>mod(c*inv(mod(k.row,29),29),29)===k.value)) reciprocalScale.push(c);
assert.equal(reciprocalScale.length,0);
for(const r of relations) assert.equal(r.matches.every(Boolean),false);
const best=Math.max(...relations.map(r=>r.matches.filter(Boolean).length));
assert.equal(best,1);
console.log(JSON.stringify({status:"PASS",known,relations,freeAffineFits:affine,scaledReciprocalFits:reciprocalScale,bestNamedRelationMatches:best,conclusion:"No predeclared inverse, DH-exponent/public-share, reciprocal-scale, or even free affine GP29 map explains all three frozen K-column state pairs. The triple is non-identifying, so no fourth K-column value is opened."},null,2));
