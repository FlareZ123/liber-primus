/**
 * Original LP2 directed GP29 pair-multiplicity gate for a repeated complete
 * nonloop digraph traversal. Tests original off-diagonal ordered-pair counts
 * against both an exact 29-vertex Eulerian positive and a source-repeat-masked
 * random predecessor-excluding control. No invented plaintext or keys.
 *
 * SFT: node sims/lp2_directed29_edge_cycle_original_sft.cjs
 */
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const corpus = JSON.parse(fs.readFileSync(path.resolve(__dirname,
  "../resources/liber-primus/lp2-corpus.json"), "utf8"));
const pages = corpus.pages.filter(p => p.page <= 55 && p.runic_count > 0);
assert.equal(pages.length, 55);
const total = pages.reduce((n,p) => n+p.indices.length,0);
assert.equal(total, 12956);
const n = 29, offSlots = n * (n-1);

/** @param {number[][]} blocks */
function audit(blocks) {
  const pair = new Uint32Array(n*n);
  let transitions=0,repeat=0;
  for(const block of blocks){
    for(let j=1;j<block.length;j++){
      const a=block[j-1],b=block[j];
      pair[a*n+b]++;
      transitions++;
      if(a===b)repeat++;
    }
  }
  const off=[];
  for(let a=0;a<n;a++)for(let b=0;b<n;b++)if(a!==b) off.push(pair[a*n+b]);
  const mean=(transitions-repeat)/offSlots;
  const chi2=off.reduce((s,v)=>s+(v-mean)*(v-mean)/mean,0);
  const histogram={};
  for(const count of off)histogram[count]=(histogram[count]||0)+1;
  return {transitions,repeat,offTransitions:transitions-repeat,
    mean,chi2,min:Math.min(...off),max:Math.max(...off),
    lowVariance:off.reduce((s,v)=>s+(v-mean)**2,0)/offSlots,
    hist:histogram,allOffPresent:off.every(v=>v>0)};
}

const actualPage=audit(pages.map(p=>p.indices));
const tape=pages.flatMap(p=>p.indices);
const actualFull=audit([tape]);
assert.equal(actualPage.transitions,12901);
assert.equal(actualPage.repeat,86);
assert.equal(actualFull.transitions,12955);
assert.equal(actualFull.repeat,86);
assert.equal(actualFull.offTransitions,12869);

/* Exhaustive directed graph on n vertices, every nonloop ordered edge once,
   generated by deterministic Hierholzer traversal. */
function eulerCycle(){
  const next=Array(n).fill(0),stack=[0],rev=[];
  while(stack.length){
    const v=stack[stack.length-1];
    while(next[v]<n&&next[v]===v)next[v]++;
    if(next[v]===n){rev.push(stack.pop());continue;}
    stack.push(next[v]++);
  }
  return rev.reverse();
}
const cycle=eulerCycle();
assert.equal(cycle.length,813);
assert.equal(cycle[0],cycle[cycle.length-1]);
const one=audit([cycle]);
assert.equal(one.repeat,0);
assert.equal(one.min,1);assert.equal(one.max,1);
const long=[cycle[0]];
for(let t=0;t<16;t++)long.push(...cycle.slice(1));
const planted=audit([long.slice(0,12956)]);
assert.equal(planted.min,15);
assert.equal(planted.max,16);

/* Condition on original page lengths AND the exact original within-page
   repeat mask; independent uniform alternatives among 28 nonprevious runes.
   Fixed xorshift32 for repeatability. */
let seed=0x6713921f;
function rnd(){seed^=seed<<13;seed^=seed>>>17;seed^=seed<<5;return seed>>>0;}
function sampled(){
  const blocks=[];
  for(const page of pages){
    const old=page.indices,seq=[rnd()%n];
    for(let j=1;j<old.length;j++){
      const prev=seq[j-1];
      seq.push(old[j]===old[j-1]?prev:(()=>{
        const rank=rnd()%(n-1);
        return rank>=prev?rank+1:rank;
      })());
    }
    blocks.push(seq);
  }
  return audit(blocks);
}
const draws=500, sampledChi=[];
let lower=0,upper=0,loMin=1000,hiMax=0;
for(let t=0;t<draws;t++){
  const res=sampled();
  sampledChi.push(res.chi2);
  if(res.chi2<=actualPage.chi2)lower++;
  if(res.chi2>=actualPage.chi2)upper++;
  loMin=Math.min(loMin,res.min);
  hiMax=Math.max(hiMax,res.max);
}
sampledChi.sort((a,b)=>a-b);
