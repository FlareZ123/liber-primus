'use strict';
/** LP2 conditional p55 full-shell fifth-root and whole-word index-five quotient. Node 22, CommonJS. */
function analyze(corpus,transcript){
  const eq=(a,b,msg)=>{if(JSON.stringify(a)!==JSON.stringify(b))throw Error(msg+`: ${JSON.stringify(a)} != ${JSON.stringify(b)}`)};
  const index=new Map(corpus.runes.map((r,i)=>[r,i]));
  const ids=s=>Array.from(s).filter(ch=>index.has(ch)).map(ch=>index.get(ch));
  const pages=transcript.split('%').filter(s=>ids(s).length);
  eq(pages.map(ids),corpus.pages.filter(p=>p.indices.length).map(p=>p.indices),"page tapes");
  const groups=s=>s.replace(/[\s/%]/g,'').split(/[^\u16a0-\u16ff]+/u).map(ids).filter(a=>a.length);
  const raw=groups(pages.slice(0,55).join('%'));
  eq(raw.length,2896,"word count");eq(raw.flat(),corpus.pages.slice(0,56).flatMap(p=>p.indices),"unknown rune tape");
  const g55=groups(pages[54]);eq(g55.map(g=>g.length),[1,4,2,2,6,6,2,13,6,4,2,7,7,2,6,3,3],"p55 fragments");
  const inner=g55.slice(1).flatMap(g=>g.slice(1,-1)),outer=[g55[0][0],...g55.slice(1).flatMap(g=>[g[0],g[g.length-1]])];
  const num=(a,base=29n)=>a.reduce((v,d)=>v*base+BigInt(d),0n);
  const digs=(v,base=29n)=>{const a=[];do{a.push(Number(v%base));v/=base}while(v);return a.reverse()};
  const P=num(inner)/8n,E=num(outer),m=(P-1n)/5n;
  eq(inner.length,43,"interior");eq(outer.length,33,"shell");
  eq((8n*P).toString(),num(inner).toString(),"prime factor");
  eq(P.toString(),"63755441409934721069036418908763882578170591536653256311514221","P");
  const pow=(x,n)=>{let y=1n;for(x%=P;n>0n;n>>=1n,x=x*x%P)if(n&1n)y=y*x%P;return y};
  const w=pow(5n,m);eq(pow(w,5n).toString(),"1","omega order");if(w===1n)throw Error("trivial character");
  const lut=new Map(Array.from({length:5},(_,k)=>[pow(w,BigInt(k)).toString(),k]));
  const label=x=>{if(x===0n)return null;const k=lut.get(pow(x,m).toString());if(k===undefined)throw Error("no quotient");return k};
  eq(label(E),0,"shell is fifth power");
  const inv5=(m+1n)/5n;eq((m%5n).toString(),"4","inverse");
  const root=pow(E,inv5);eq(label(root),0,"subgroup root");
  const roots=Array.from({length:5},(_,k)=>{const x=root*pow(w,BigInt(k))%P;eq(pow(x,5n).toString(),E.toString(),"root replay");eq(label(x),Number((BigInt(k)*m)%5n),"root class");const ds=digs(x);return {k,integer:x.toString(),width:ds.length,render:ds.map(i=>corpus.translit[i]).join(" ")}});
  eq(new Set(roots.map(x=>x.integer)).size,5,"distinct roots");
  const prefix=groups(pages.slice(0,54).join('%'));const carry=prefix.pop();eq(carry.length,10,"incoming prefix length");
  eq(prefix.flat().length,12870,"disjoint prefix runes");
  const records=prefix.map((g,i)=>({i,len:g.length,k:label(num(g))}));
  const zero=records.filter(x=>x.k===null).map(x=>x.i);
  const packets=[];let packet=[];for(const x of records){if(x.k===null){if(packet.length)packets.push(packet);packet=[]}else packet.push(x.k)}if(packet.length)packets.push(packet);
  const preview=(a)=>a.map(x=>x>=32&&x<=126?String.fromCharCode(x):".").join("");
  const triples=d=>{const a=[];for(let i=0;i+2<d.length;i+=3)a.push(d[i]*25+d[i+1]*5+d[i+2]);return a};
  const bytesFrom=d=>digs(num(d,5n),256n);
  const analyzePacket=d=>{const n=num(d,5n),bytes=bytesFrom(d);eq(num(bytes,256n).toString(),n.toString(),"byte replay");
    const tri=triples(d);const hex=bytes.map(x=>x.toString(16).padStart(2,'0')).join('');
    return {digits:d.length,firstDigits:d.slice(0,24).join(""),base5ToBytes:{bytes:bytes.length,headHex:hex.slice(0,64),printable:bytes.filter(x=>x>=32&&x<=126).length,openPGPHeaderHighBit:Boolean(bytes[0]&128),preview:preview(bytes.slice(0,120)),fullHex:hex},pairRemainder:d.length%2,tripletASCII:{count:tri.length,remainder:d.length%3,printable:tri.filter(x=>x>=32&&x<=126).length,preview:preview(tri.slice(0,180)),fullPreview:preview(tri)}};
  };
  const packetResults=packets.map(analyzePacket);
  const fixedText="THE WORDS ARE THE MAP",ascii=Array.from(fixedText,ch=>ch.charCodeAt(0));
  const fixedDigits=ascii.flatMap(n=>[Math.floor(n/25),Math.floor(n/5)%5,n%5]);
  const repCache=new Map();
  const representative=(k,L)=>{const key=k+":"+L;if(repCache.has(key))return repCache.get(key);
    for(let x=29n**BigInt(L-1);x<29n**BigInt(L);x++){if(label(x)===k){repCache.set(key,x);return x}}throw Error("no length-matched representative")};
  const embed=d=>d.map((k,i)=>{const L=prefix[i].length,x=representative(k,L);eq(digs(x).length,L,"control geometry");return x});
  const plantedTriple=embed(fixedDigits);eq(plantedTriple.map(label),fixedDigits,"quotient control");
  const recovered=String.fromCharCode(...triples(plantedTriple.map(label)));eq(recovered,fixedText,"ASCII control");
  const packedDigits=digs(num(ascii,256n),5n),plantedPacked=embed(packedDigits);
  eq(bytesFrom(plantedPacked.map(label)),ascii,"packed-byte control");
  const native57=groups(pages[56]).map(g=>label(num(g)));
  return {P:P.toString(),E:E.toString(),omega:w.toString(),roots,wordCount:prefix.length,runeCount:prefix.flat().length,zero,labels:Array.from({length:5},(_,k)=>records.filter(x=>x.k===k).length),packets:packetResults,control:{plaintext:recovered,tripletWords:fixedDigits.length,packedWords:packedDigits.length,matchingWordLengths:true,native57:native57.join("")}};
}
const fs=require('node:fs');
const path=require('node:path');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const output=analyze(JSON.parse(read('resources/liber-primus/lp2-corpus.json')),read('resources/lp2-transcription.txt'));
console.log(JSON.stringify(output,null,2));
