// Exhaustive source-derived Blum modulus GP29 plaintext recovery using the
// six conventional five/eight-bit byte-to-rune transports. Windows Node22 SFT.
'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { buildCleanNativeTrigram } = require('./lp2_agent15_clean_lp1_trigram.cjs');

const root = path.join(__dirname, '..');
const corpus = JSON.parse(fs.readFileSync(path.join(root, 'resources', 'liber-primus', 'lp2-corpus.json'), 'utf8'));
const referenceText = fs.readFileSync(path.join(root, 'resources', 'liber-primus', 'lp1-plaintext-reference.txt'), 'utf8');
const model = buildCleanNativeTrigram({corpus, referenceText});
const p55 = corpus.pages.find((p) => p.page === 55).indices.slice(1);
const clear = corpus.pages.find((p) => p.page === 57).indices.slice(0, 75);
assert.equal(p55.length, 75);
assert.equal(clear.length, 75);

const Q=29;
const M=1259*1031;
const n=35;
const sourceSeedState=1229*1229%M;
const bi=new Int32Array(Q*Q);
const tri=new Int32Array(Q*Q*Q);
const prob=new Float64Array(Q*Q*Q);
const trainingSegments=model.trainingSegments;
for(const training of trainingSegments)for(let i=2;i<training.length;i++){
 const k=Q*training[i-2]+training[i-1];
 bi[k]++;
 tri[Q*k+training[i]]++;
}
for(let i=0;i<Q*Q;i++)for(let c=0;c<Q;c++)
 prob[Q*i+c]=Math.log((tri[Q*i+c]+1)/(bi[i]+Q));

/** @param {number[]} arr @returns {number} */
function score(arr){
 let log=0;
 for(let i=2;i<arr.length;i++)
   log+=prob[Q*(Q*arr[i-2]+arr[i-1])+arr[i]];
 return log/(arr.length-2);
}
assert.ok(Math.abs(score(clear)-model.scoreStream(clear).mean)<1e-12);
const positiveScore=score(clear.slice(0,n));

/** @typedef {{label:string,bits:number,lsb:boolean,reject:boolean}} Mode */
const modes=[
 {label:'5bit-mod29-MSB',bits:5,lsb:false,reject:false},
 {label:'5bit-reject-MSB',bits:5,lsb:false,reject:true},
 {label:'8bit-mod29-MSB',bits:8,lsb:false,reject:false},
 {label:'5bit-mod29-LSB',bits:5,lsb:true,reject:false},
 {label:'5bit-reject-LSB',bits:5,lsb:true,reject:true},
 {label:'8bit-mod29-LSB',bits:8,lsb:true,reject:false}
];

/**
 * Complete exact state generator. Every post-square state belongs to a
 * subgroup with squared-map period dividing 1224, so if rejecting all 1225
 * consecutive group draws never emits, no future group can emit either.
 * @param {number} startingState
 * @param {number} length
 * @param {Mode} mode
 * @returns {number[] | null}
 */
function generate(startingState,length,mode){
 const out=[];
 let state=startingState;
 while(out.length<length){
  let k=0,rejects=0;
  while(true){
   k=0;
   for(let bit=0;bit<mode.bits;bit++){
     state=state*state%M;
     k|=(state&1)<<(mode.lsb?bit:mode.bits-1-bit);
   }
   if(!mode.reject||k<Q)break;
   rejects++;
   if(rejects>1224)return null;
  }
  out.push(k%Q);
 }
 return out;
}

/**
 * @param {{state:number,sign:number,screen:number}[]} top
 * @param {{state:number,sign:number,screen:number}} entry
 */
function insertTop(top,entry){
 if(top.length>=12&&entry.screen<=top[top.length-1].screen)return;
 top.push(entry);
 top.sort((a,b)=>b.screen-a.screen);
 if(top.length>12)top.pop();
}

/** @param {number[]} cipher @param {number[]} key @param {number} sign @returns {number[]} */
function decoded(cipher,key,sign){
 return cipher.map((c,i)=>(c+sign*key[i]+Q)%Q);
}

const reports=[];
for(const mode of modes){
 const plantedKey=generate(sourceSeedState,75,mode);
 assert.ok(plantedKey,mode.label+' must decode the original-source planted seed');
 const plant=clear.map((p,i)=>(p+plantedKey[i])%Q);
 assert.deepEqual(decoded(plant,plantedKey,-1),clear);

 const bestOriginal=[],bestPlant=[];
 let sourceAboveClear=0;
 let undecodableStates=0;
 let plantedStateSeen=false;
 for(let initial=0;initial<M;initial++){
  const key=generate(initial,n,mode);
  if(!key){undecodableStates++;continue;}
  for(const sign of [-1,1]){
   const nativeScore=score(decoded(p55.slice(0,n),key,sign));
   const plantScore=score(decoded(plant.slice(0,n),key,sign));
   if(nativeScore>=positiveScore)sourceAboveClear++;
   if(initial===sourceSeedState&&sign===-1&&Math.abs(plantScore-positiveScore)<1e-10)
      plantedStateSeen=true;
   insertTop(bestOriginal,{state:initial,sign,screen:nativeScore});
   insertTop(bestPlant,{state:initial,sign,screen:plantScore});
  }
 }
 assert.ok(plantedStateSeen,mode.label+' genuine plant must be generated by scan');
 assert.ok(bestPlant.some((v)=>v.state===sourceSeedState&&v.sign===-1),
   mode.label+' planted true key must rank in top list');
 const full=(arr,cipher)=>arr.map(({state,sign,screen})=>{
  const key=generate(state,75,mode);
  assert.ok(key);
  const plain=decoded(cipher,key,sign);
  return {state,sign,screen,full:score(plain),
    holdout:score(plain.slice(n)),text:model.spell(plain)};
 });
 reports.push({
  mode:mode.label, testedStates:M, twoSigns:true, undecodableStates,
  originalAtOrAboveClear35:sourceAboveClear, independentClear35:positiveScore,
  originalBestByScreen:full(bestOriginal,p55).slice(0,4),
  positiveBestByScreen:full(bestPlant,plant).slice(0,3)
 });
 console.log(mode.label+': completed '+M+' states; original >= clear p57: '+sourceAboveClear);
}
const output={source:'original p55 75 complete-word runes; LP1 3,510 native GP29 training; p57 positive',
 testedStatesPerMode:M, conventionalModes:modes.length, first35ClearScore:positiveScore,
 full75P57Score:score(clear),full75RawP55Score:score(p55),reports};
console.log(JSON.stringify(output,null,2));
console.log('PASS: 6 original p55 BBS state/register inverses and planted native controls');
