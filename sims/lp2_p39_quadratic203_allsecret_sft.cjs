/**
 * All-key original-LP2 test of the p39 red quadratic as a two-state GF(29)
 * additive stream cipher. Run: node sims/lp2_p39_quadratic203_allsecret_sft.cjs
 *
 * The visible p39 rune triple at local 119 is [27,5,15]. Interpreting it as
 * constant-first coefficients gives 15(X-24)^2. This is a HYPOTHESIS about
 * its cipher role, not a recovered author instruction.
 *
 * Every additive pad from the corresponding two-state recurrence is periodic
 * with period dividing 203. Coincidence at equal phases modulo203 is invariant
 * under every pair of unknown initial states and both cipher signs. The exact
 * comparison uses all 3,000 p40-53 body runes and 300 GP-native, original
 * printed-word-length-matched Gibran controls.
 */

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const {parseLP2Words} = require("./lp2_word_pages.cjs");

const root = path.resolve(__dirname, "..");
const corpus = JSON.parse(fs.readFileSync(path.join(
  root, "resources/liber-primus/lp2-corpus.json"), "utf8"));
const transcript = fs.readFileSync(path.join(
  root, "resources/liber-primus/lp2-transcription.txt"), "utf8");
const prose = fs.readFileSync(path.join(
  root, "resources/control/gibran_prophet_58585.txt"), "utf8");
const mod = n => ((n % 29) + 29) % 29;
const period = 203;

const triad = corpus.pages.find(p => p.page === 39).indices.slice(119, 122);
assert.deepEqual(triad, [27, 5, 15]);
assert.deepEqual([mod(2 * triad[0]), mod(2 * triad[1]), 1],
  [25, 10, 1], "The marked quadratic must equal (X-24)^2");
assert.equal(mod(24 ** 7), 1, "The eigenvalue must have order 7");
assert.notEqual(mod(24), 1);

const bodyPages = corpus.pages.filter(p => p.page >= 40 && p.page <= 53);
const entireChapter = bodyPages.flatMap(p => p.indices);
assert.equal(entireChapter.length, 3008);
assert.deepEqual(entireChapter.slice(0, 8), [0, 9, 19, 26, 6, 23, 25, 8]);
const cipher = entireChapter.slice(8);
assert.equal(cipher.length, 3000);

/** @param {number} a @param {number} b @param {number} n
 * @returns {number[]} 203-periodic LFSR generated by (X-24)^2. */
function pad(a, b, n) {
  const k = [a, b];
  for (let i = 2; i < n; i++) k.push(mod(4 * k[i - 2] + 19 * k[i - 1]));
  return k.slice(0, n);
}

/** @param {number[]} symbols
 * @returns {{pairs:number,total:number,rate:number}} */
function phasePairs(symbols) {
  const buckets = Array.from({length: period}, () => new Int32Array(29));
  let pairs = 0;
  let total = 0;
  for (let i = 0; i < symbols.length; i++) {
    const slot = i % period;
    pairs += buckets[slot][symbols[i]];
    total += Math.floor(i / period);
    buckets[slot][symbols[i]]++;
  }
  return {pairs, total, rate: pairs / total};
}

const original = phasePairs(cipher);
assert.deepEqual(original, {pairs: 745, total: 20685,
  rate: 745 / 20685});

// The two basis states prove the recurrence matrix itself has 203-periodic
// output, hence *every* secret seed pair and either sign does. Exhaustively
// assert the original equality invariant for 841 seeds x 2 signs.
for (const [a, b] of [[1, 0], [0, 1]]) {
  const k = pad(a, b, period * 2);
  assert.deepEqual(k.slice(0, period), k.slice(period));
}
for (let a = 0; a < 29; a++) {
  for (let b = 0; b < 29; b++) {
    const key = pad(a, b, cipher.length);
    assert.equal(key[0], key[period]);
    assert.equal(key[1], key[period + 1]);
    for (const sign of [-1, 1]) {
      const decrypted = cipher.map((v, i) => mod(v + sign * key[i]));
      assert.equal(phasePairs(decrypted).pairs, original.pairs);
      for (let i = 0; i < cipher.length; i++) {
        assert.equal(mod(decrypted[i] - sign * key[i]), cipher[i]);
      }
    }
  }
}

const parsed = parseLP2Words(transcript);
assert.equal(parsed.words.length, 2896);
assert.equal(parsed.runeCount, 12956);
const chapterWords = parsed.words.filter(w => w.startPage >= 40 && w.startPage <= 52);
assert.deepEqual(chapterWords.slice(0, 2).map(w => w.length), [3, 5]);
const lengths = chapterWords.slice(2).map(w => w.length);
assert.equal(lengths.length, 667);
assert.equal(lengths.reduce((a, b) => a + b, 0), cipher.length);

// Match ALL original word lengths without using any ciphertext symbol
// in control selection. The conversion matches this repository's established
// GP normalization convention, including multi-rune English digraphs.
const runeIndex = new Map(corpus.translit.map((s, i) => [s, i]));
runeIndex.set("ING", runeIndex.get("NG"));
runeIndex.set("IO", runeIndex.get("EO"));
const multigraphs = ["ING", "TH", "NG", "EO", "OE", "AE", "IA", "EA", "IO"];

/** @param {string} word @returns {number[]} */
function gpWord(word) {
  const text = word.toUpperCase().replace(/QU/g, "CW")
    .replace(/V/g, "U").replace(/[KQ]/g, "C").replace(/Z/g, "S");
  const result = [];
  for (let i = 0; i < text.length;) {
    const group = multigraphs.find(s => text.startsWith(s, i));
    const symbol = group === undefined ? text[i] : group;
    const index = runeIndex.get(symbol);
    assert.notEqual(index, undefined, "Unencodable native symbol: " + symbol);
    result.push(index);
    i += symbol.length;
  }
  return result;
}

const bins = Array.from({length: 24}, () => []);
for (const word of prose.match(/[A-Za-z]+/g) || []) {
  const symbols = gpWord(word);
  if (symbols.length < bins.length) bins[symbols.length].push(symbols);
}
for (const length of lengths) assert(bins[length].length > 0);

let seed = 0x290203;
/** @returns {number} */
function random32() {
  seed ^= seed << 13;
  seed ^= seed >>> 17;
  seed ^= seed << 5;
  return seed >>> 0;
}

const controls = [];
let firstPlain = [];
for (let trial = 0; trial < 300; trial++) {
  const native = [];
  for (const length of lengths) {
    const pool = bins[length];
    native.push(...pool[random32() % pool.length]);
  }
  assert.equal(native.length, cipher.length);
  if (trial === 0) firstPlain = native;
  controls.push(phasePairs(native).rate);
}
controls.sort((a, b) => a - b);
assert(Math.abs(controls[0] - 0.05458061397147691) < 1e-12);
assert(Math.abs(controls[149] - 0.05975344452501813) < 1e-12);
assert(Math.abs(controls[299] - 0.06540971718636693) < 1e-12);
assert(original.rate < controls[0]);

const plantedKey = pad(9, 24, firstPlain.length);
const plantedCipher = firstPlain.map((v, i) => mod(v + plantedKey[i]));
const nativePhase = phasePairs(firstPlain);
const plantedPhase = phasePairs(plantedCipher);
assert.deepEqual(plantedPhase, nativePhase);
assert.equal(plantedPhase.pairs, 1205);
assert.deepEqual(plantedCipher.map((v, i) => mod(v - plantedKey[i])),
  firstPlain);

// Every arbitrary fixed outer GP29 alphabet permutation also preserves
// equality at the same autonomous key phase. Test a nontrivial secret
// bijection and its explicit inverse without choosing any original key.
const plantedOuter = plantedCipher.map(v => mod(7 * v + 3));
assert.deepEqual(phasePairs(plantedOuter), nativePhase);
assert.deepEqual(plantedOuter.map((v, i) =>
  mod(25 * (v - 3) - plantedKey[i])), firstPlain);


/** @param {number} cipherRune
 * @param {"indices"|"prime"} register */
function forcingValue(cipherRune, register) {
  return register === "indices" ? cipherRune : corpus.prime[cipherRune] % 29;
}

/** Known particular solution with both starting states fixed at zero.
 * @param {number[]} observedCipher
 * @param {"indices"|"prime"} register */
function particularPad(observedCipher, register) {
  const k = new Array(observedCipher.length).fill(0);
  for (let i = 0; i + 2 < k.length; i++) {
    k[i + 2] = mod(19 * k[i + 1] + 4 * k[i] +
      forcingValue(observedCipher[i], register));
  }
  return k;
}

/** Authentic plaintext-dependent output only through *published ciphertext*
 * (standard known-ciphertext forcing); original ciphertext determines the pad
 * recurrence and all unobserved key choices are solely two seed runes.
 * @param {number[]} plain
 * @param {"indices"|"prime"} register
 * @param {number} sign +1 or -1
 * @param {number} first
 * @param {number} second */
function feedbackEncrypt(plain, register, sign, first, second) {
  const k = new Array(plain.length).fill(0);
  k[0] = first;
  k[1] = second;
  const cipherOut = [];
  for (let i = 0; i < plain.length; i++) {
    cipherOut.push(mod(plain[i] + sign * k[i]));
    if (i + 2 < plain.length) {
      k[i + 2] = mod(19 * k[i + 1] + 4 * k[i] +
        forcingValue(cipherOut[i], register));
    }
  }
  return cipherOut;
}

/** @param {number[]} cipherIn
 * @param {"indices"|"prime"} register
 * @param {number} sign
 * @param {number} first
 * @param {number} second */
function feedbackDecrypt(cipherIn, register, sign, first, second) {
  const k = new Array(cipherIn.length).fill(0);
  k[0] = first;
  k[1] = second;
  const plain = [];
  for (let i = 0; i < cipherIn.length; i++) {
    plain.push(mod(cipherIn[i] - sign * k[i]));
    if (i + 2 < cipherIn.length) {
      k[i + 2] = mod(19 * k[i + 1] + 4 * k[i] +
        forcingValue(cipherIn[i], register));
    }
  }
  return plain;
}

// An independently selected, finite stateful variant: inject the preceding
// ciphertext's GP29 index or GP prime-value residue into the same red-Q
// recurrence. Every forced stream = particularPad(observed) + 203-periodic
// homogeneous state. Subtracting the known particular pad yields an exactly
// key-independent same-phase collision count, even with aperiodic CFB forcing.
const feedbackVariants = [];
for (const register of ["indices", "prime"]) {
  const particular = particularPad(cipher, register);
  for (const sign of [1, -1]) {
    const adjusted = cipher.map((v, i) => mod(v - sign * particular[i]));
    const observed = phasePairs(adjusted);
    const expected = register === "indices"
      ? (sign === 1 ? 736 : 700)
      : (sign === 1 ? 739 : 685);
    assert.equal(observed.pairs, expected);
    assert.equal(observed.total, 20685);
    const nativeOriginal = feedbackEncrypt(firstPlain, register, sign, 9, 24);
    assert.deepEqual(feedbackDecrypt(nativeOriginal, register, sign, 9, 24),
      firstPlain);
    const nativeParticular = particularPad(nativeOriginal, register);
    const adjustedNative = nativeOriginal.map(
      (v, i) => mod(v - sign * nativeParticular[i]));
    assert.equal(phasePairs(adjustedNative).pairs, nativePhase.pairs);
    feedbackVariants.push({forcing: register, cipherSign: sign,
      keyIndependentOriginal: observed,
      positiveNativePairs: phasePairs(adjustedNative).pairs});
  }
}

