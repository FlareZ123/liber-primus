'use strict';
/**
 * Source-exact p7 red 2-input/2-output GP29 butterfly, integer
 * Pythagorean/Berggren bridge and p8-p14 literal seven phase marker.
 * Reconstruct authentic printed words, page-carry and ink annotations.
 * Windows 11 / Node.js 22 single-file read-only SFT.
 */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = path.join(__dirname, '..', 'resources', 'liber-primus');
/** @param {string} name @returns {string} */
const read = name => fs.readFileSync(path.join(base, name), 'utf8');
const gp = JSON.parse(read('lp2-corpus.json'));
const ink = JSON.parse(read('lp2-ink-annotations.json'));
const sections = read('lp2-transcription.txt').split('%');
const index = new Map(gp.runes.map((r, i) => [r, i]));
const red = new Map(ink.pages.map(p => [p.page, new Set(
  (p.red_spans || []).flatMap(s =>
    Array.from({ length: s.length }, (_, k) => s.start + k)))]));
/** @param {number} x @returns {number} */
const mod = x => (x % 29 + 29) % 29;
/** @typedef {{page:number,index:number,value:number,red:boolean}} Cell */
/** @type {Cell[][]} */
const words = [];
/** @type {Cell[]} */
let nextWord = [];
for (let page = 0; page <= 55; page++) {
  if (page === 50) continue;
  const chars = sections[page > 50 ? page - 1 : page];
  let offset = 0;
  for (const char of chars) {
    if (index.has(char)) {
      nextWord.push({ page, index: offset, value: index.get(char),
        red: red.get(page)?.has(offset) || false });
      offset++;
    } else if ((char === '-' || char === '.') && nextWord.length) {
      words.push(nextWord);
      nextWord = [];
    }
  }
  assert.equal(offset, gp.pages[page].indices.length);
}
if (nextWord.length) words.push(nextWord);
assert.equal(words.length, 2896);
assert.deepEqual(words.flat().map(x => x.value),
  gp.pages.slice(0, 56).flatMap(p => p.indices));
const redWords = page => words.filter(w =>
  w[0].page === page && w.every(x => x.page === page && x.red));
const product = w => w.reduce((s, x) => mod(s * x.value), 1);
const p7 = redWords(7), p8 = redWords(8);
const coeff = p7.map(product);
const heading = p8.map(product);
assert.deepEqual(coeff, [11, 26, 8, 15, 2]);
assert.deepEqual(heading, [4, 3]);
assert.equal(p8.at(-1).at(-1).value, 17);

/** @param {number} a @param {number} b @returns {number[]} */
function forward(a, b) { return [mod(a + b), mod(b - a)]; }
/** @param {number} u @param {number} v @returns {number[]} */
function inverse(u, v) { return [mod(15 * (u - v)), mod(15 * (u + v))]; }
assert.deepEqual(forward(coeff[0], coeff[1]), coeff.slice(2, 4));
assert.deepEqual(inverse(...coeff.slice(2, 4)), coeff.slice(0, 2));
assert.equal(mod(1 * 1 - 1 * -1), coeff[4]); // det[[1,1],[-1,1]]=2.
for (let a = 0; a < 29; a++)
  for (let b = 0; b < 29; b++)
    assert.deepEqual(inverse(...forward(a, b)), [a, b]);

// Both source p8 whole-word outputs are Euclid m=2's 3-4-5 legs,
// with the hypotenuse independently generated by the p7 polynomial.
const euclid = m => [m * m - 1, 2 * m, m * m + 1];
assert.deepEqual(euclid(2), [3, 4, 5]);
assert.deepEqual(euclid(4), [15, 8, 17]); // primitive Berggren C-child
assert.deepEqual([coeff[3], coeff[2], p8.at(-1).at(-1).value],
  euclid(4));
assert.equal(coeff[2] ** 2 + coeff[3] ** 2, 17 ** 2);

/** @param {number[]} c @param {number} x @returns {number} */
const poly = (c, x) => c.reduceRight((s, a) => mod(s * x + a), 0);
/** @param {number[]} c @param {number} x @returns {number} */
const derivative = (c, x) => mod(c.reduce((s, a, k) =>
  s + (k > 0 ? k * a * x ** (k - 1) : 0), 0));
let pState = 0;
const precycle = [];
for (let i = 0; i < 5; i++) {
  precycle.push(pState);
  pState = poly(coeff, pState);
}
assert.deepEqual(precycle, [0, 11, 23, 17, 18]);
assert.equal(pState, 5);
const cycle = [];
for (let i = 0; i < 7; i++) {
  cycle.push(pState);
  pState = poly(coeff, pState);
}
assert.deepEqual(cycle, [5, 15, 28, 9, 10, 24, 7]);
assert.equal(pState, 5);
assert.deepEqual([poly(coeff, 3), poly(coeff, 4),
  derivative(coeff, 4)], [3, 4, 17]);

// Exactly one Arabic numeral in original p8-p14; preserve the rune tape
// and count the number of GP ciphertext runes physically before it.
let numberEvents = [], globalRune = 0;
for (let page = 8; page <= 14; page++) {
  for (const ch of sections[page]) {
    if (index.has(ch)) globalRune++;
    else if (ch >= '0' && ch <= '9')
      numberEvents.push({ page, numeral: ch, precedingRunes: globalRune });
  }
}
assert.equal(globalRune, 1729);
assert.deepEqual(numberEvents,
  [{ page: 10, numeral: '7', precedingRunes: 692 }]);
assert.equal(692 % 7, 6);
assert.equal(cycle[692 % 7], 7);       // whole-chapter phase-zero marker
assert.equal(cycle[(692 - 12) % 7], 15); // black-only clock counterexample

// All-degree-four candidate polynomials with fixed historical p8
// constraints P(3)=3,P(4)=4,P'(4)=17, no fitted language.
const inverseThree = [[16,14,12],[21,8,22],[1,28,1]];
let considered = 0, butterflyCount = 0, triangleCount = 0,
  triangleRootCount = 0, butterflyOriginal = [];
for (let c3 = 0; c3 < 29; c3++) {
  for (let c4 = 0; c4 < 29; c4++) {
    const rhs = [
      mod(3 - 27 * c3 - 81 * c4),
      mod(4 - 64 * c3 - 256 * c4),
      mod(17 - 48 * c3 - 256 * c4)
    ];
    const cs = inverseThree.map(row =>
      mod(row.reduce((sum, x, i) => sum + x * rhs[i], 0)));
    const c = [...cs, c3, c4];
    assert.deepEqual([poly(c, 3), poly(c, 4), derivative(c, 4)],
      [3,4,17]);
    considered++;
    const isButterfly = c[4] === 2 && mod(c[0]+c[1]) === c[2] &&
      mod(c[1]-c[0]) === c[3];
    if (isButterfly) { butterflyCount++; butterflyOriginal.push(c); }
    const isSourceTriangle = (c[2] === 8 && c[3] === 15) ||
      (c[2] === 15 && c[3] === 8);
    if (isSourceTriangle) {
      triangleCount++;
      const roots = Array.from({length:29},(_,j)=>j)
        .filter(x=>poly(c,x)===x);
      if (roots.join(',') === '3,4') triangleRootCount++;
    }
  }
}
assert.deepEqual([considered,butterflyCount,triangleCount,triangleRootCount],
  [841,1,2,1]);
assert.deepEqual(butterflyOriginal, [coeff]);

/** @param {number[]} tape @param {'forward'|'inverse'} mode
 * @returns {number[]} */
function transform(tape, mode) {
  const out = [];
  for (let i = 0; i < tape.length; i += 2) {
    if (i + 1 === tape.length) { out.push(tape[i]); break; }
    out.push(...(mode === 'forward' ?
      forward(tape[i], tape[i+1]) : inverse(tape[i], tape[i+1])));
  }
  return out;
}
/** @param {number[]} values @returns {number} */
function ioc(values) {
  const f = Array(29).fill(0);
  for (const x of values) f[x]++;
  return f.reduce((s, n) => s + n * (n-1), 0) /
    (values.length * (values.length-1));
}
const regions = {
  p8BlackAndGenuineP9Carry: gp.pages[8].indices.slice(12)
    .concat(gp.pages[9].indices[0]),
  p8WholeAndGenuineP9Carry: gp.pages[8].indices
    .concat(gp.pages[9].indices[0]),
  p9to14Complete: gp.pages.slice(9, 15).flatMap(p => p.indices),
  p16to21Holdout: gp.pages.slice(16, 22).flatMap(p => p.indices),
  p40to53Holdout: gp.pages.slice(40, 54).flatMap(p => p.indices)
};
assert.deepEqual(Object.values(regions).map(x=>x.length),
  [244,256,1474,1613,3008]);
const originalReadouts = [];
for (const [label, tape] of Object.entries(regions)) {
  for (const mode of ['forward','inverse']) {
    const result = transform(tape, mode);
    const reverse = transform(result, mode==='forward'?'inverse':'forward');
    assert.deepEqual(reverse,tape);
    assert(ioc(result)<0.037);
    originalReadouts.push({label,mode,n:tape.length,ioc:ioc(result)});
  }
}
// Genuinely clear LP2 p57 native positive, odd final rune preserved.
const native=gp.pages[57].indices;
assert.equal(native.length,95);
for(const mode of ['forward','inverse'])
  assert.deepEqual(transform(transform(native,mode),
    mode==='forward'?'inverse':'forward'),native);
console.log(JSON.stringify({
  exactSourceFiveWords: coeff,p8RedWords: heading,
  butterfly: {matrix:[[1,1],[-1,1]],determinant2:true,
    forward:[8,15],inverse:[11,26]},
  euclidBase:euclid(2),euclidDouble:euclid(4),
  fixedP7PolynomialCycle:cycle,
  literalSevenMarker: numberEvents[0],
  fullPageClockExpectedSeven: cycle[692%7],
  blackOnlyClockExpectedFifteen: cycle[(692-12)%7],
  conditionalSourceFamily:{
    previousThreeConstraints: considered,
    matchesSourceButterfly:butterflyCount,
    matchesMiddleEightFifteen: triangleCount,
    middleEightFifteenAndOnlyRootsThreeFour: triangleRootCount
  },
  originalReadouts,positiveP57RuneCount: native.length,
  plaintextRecovered: false
},null,2));
console.log('PASS: original red butterfly, Pythagorean bridge, numeral7 phase and complete negative decoder');
